export const VIEWER_MESSAGE_LOCALES = Object.freeze(['ko', 'zh-CN', 'zh-TW']);
export const VIEWER_MESSAGES = Object.freeze(Object.fromEntries(VIEWER_MESSAGE_LOCALES.map((locale,index) =>
  [locale,Object.freeze(Object.fromEntries(rows.map(row => [row[0],row[index]])))])));
export const VIEWER_LOCALE_OPTIONS = Object.freeze(VIEWER_MESSAGE_LOCALES.map((locale,index) =>
  Object.freeze([locale,['한국어','简体中文','繁體中文'][index]])));

function messagesFor(locale) {
  if (!Object.hasOwn(VIEWER_MESSAGES,locale)) throw new RangeError(`Unsupported viewer UI locale: ${locale}`);
  return VIEWER_MESSAGES[locale];
}
function interpolate(message, values) {
  return message.replace(/\{([a-zA-Z][\w]*)\}/g, (placeholder,name) => {
    if (!Object.hasOwn(values,name)) throw new Error(`Missing viewer message value: ${name}`);
    return String(values[name]);
  });
}
/** Strict lookup for migrated UI: missing keys/locales/values are visible development errors. */
export function t(locale,key,values={}) {
  const messages=messagesFor(locale);
  if (!Object.hasOwn(messages,key)) throw new Error(`Unknown viewer message: ${key}`);
  return interpolate(messages[key],values);
}
/** Explicit legacy boundary: uncovered labels retain their original text, never generated content.
 * Callers can collect uncovered labels through onMissing; this is not full-app translation.
 */
export function translateViewerText(locale,originalKorean,values={},onMissing) {
  const messages=messagesFor(locale);
  if (!Object.hasOwn(messages,originalKorean)) {
    onMissing?.({locale,key:originalKorean});
    return originalKorean;
  }
  return interpolate(messages[originalKorean],values);
}
