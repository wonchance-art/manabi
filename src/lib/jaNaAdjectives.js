/** な형용사인가 — 새 분석의 표식(na_stem) 또는 명사 · 형용동사로 분석된 목록 단어(문맥 없이: 단어장 · 복습). */
export function isJaNaAdjective(token) {
  if (!token) return false;
  if (token.na_stem) return true;
  const pos = token.pos || '';
  return (pos === '명사' || pos === '형용동사' || pos === 'な형용사' || pos === '') && JA_NA_ADJECTIVES.has(token.base_form || token.word_text || token.text);
}

// 명사로 쓰인 자리 — 바로 뒤가 격 · 주제 조사(自由を · 安全は · 危険の)면 그 문장의 품사는 명사다.
// な · に · で · だ(형용 활용)와 문장 끝은 な형용사로 둔다. 분석기 표식(形容動詞語幹)도 문맥을 보지 않으니 같이 거른다.
const NOUN_USE_NEXT = new Set(['を', 'が', 'は', 'の', 'も', 'へ', 'と', 'から', 'まで', 'より', 'や']);

/** 읽기 카드용 — 본문 순서(sequence)에서 이 토큰 바로 뒤(같은 줄)가 명사 쓰임 조사인가. */
export function jaNaNounUseAt(sequence, dictionary, id) {
  if (!Array.isArray(sequence) || !dictionary || !id) return false;
  const at = sequence.indexOf(id);
  if (at < 0) return false;
  const line = /^id_(\d+)_/.exec(id)?.[1];
  const nextId = sequence[at + 1];
  if (!nextId || /^id_(\d+)_/.exec(nextId)?.[1] !== line) return false;
  const next = dictionary[nextId];
  return !!next && next.pos === '조사' && NOUN_USE_NEXT.has(String(next.text || ''));
}

/** 화면 품사 — 일본어 な형용사면 「な형용사」, 아니면 저장된 품사 그대로(단어장 칩 · 복습). */
export function jaDisplayPos(word) {
  if (word?.language !== 'Japanese') return word?.pos || '';
  return isJaNaAdjective({ word_text: word.word_text, pos: word.pos }) ? 'な형용사' : (word.pos || '');
}
