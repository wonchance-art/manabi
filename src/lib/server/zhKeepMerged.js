// 서버 전용 — x-태그 되가름의 병합 유지 허용목록 (v2-T R1, 오너 승인 2026-09-01).
// 경성 사전(zhNeutralTone)·POS_FIX와 같은 화이트리스트 계층 패턴: 등재분만 예외, 밖은 규칙대로.
//
// ── 왜 목록이 필요한가
// jieba의 HMM은 사전에 없는 한자 조합을 붙여 `x` 태그를 단다. 그 대부분은 가짜 단어라
// 되가르는 것이 맞지만(교재 실측: 고유 158종 중 153종이 오병합), **진짜 신조어와 인명**은
// 사전에 없어서 x가 되는 것이라 되가르면 실단어가 부서진다. 그 소수만 여기 담는다.
//
// ── 왜 이 방향으로 기울이나 (복구 비대칭)
// 오분리(扫码 → 扫|码)는 학습자가 드래그 범위 지정으로 되붙일 수 있다
// (`useTokenRangeSelect` → `composeRangeText`). 오병합(人要)은 **분리 액션 자체가 없다** —
// `tokenEditOptions`는 뜻·발음·품사만 고친다. 되돌릴 수 있는 쪽으로 기본값을 둔다.
//
// ── 시드 근거 (전부 실측)
// 扫码·网红: 설계가 든 신조어 — HMM off로 재검하면 扫|码 · 网|红으로 부서진다.
// 好用·点餐: 우리 교재 x-토큰 158종 전수에서 건진 실단어 2종.
// 小明·小王·李明: 교재 인물명. 3자 인명(王小明·李雪梅)은 jieba가 `nr`로 제대로 잡지만
//   2자 인명은 x로 떨어진다. 성씨 판별 규칙은 오탐이 크다(李=자두·王=왕) — 목록이 맞다.
