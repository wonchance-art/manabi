// 병음 조판 폭 — 병음 토글 시 한자 간격이 변하지 않게 하는 폭 예약 규칙(오너 요청 2026-08-19).
//
// 배경: 네이티브 <ruby>는 rt가 base보다 넓으면 base를 밀어 셀을 넓힌다. 중국어 병음은
// chuāng·shuāng처럼 6자 음절이 있어 한자 1em을 넘기므로, 병음을 켜고 끌 때마다 글자가
// 좌우로 밀렸다(요미가나는 대개 base 안에 들어와 이 문제가 드러나지 않았다).
// 표준 속성 ruby-overhang은 브라우저가 사실상 구현하지 않아 무력하다.
//
// 해법: rt를 절대배치로 빼 base 폭 계산에서 제외한다(간격 변화 0). 남는 문제는 긴 병음이
// 이웃 위로 넘쳐 겹치는 것인데, 이때 **폭을 넓히면 안 된다** — 글자마다 폭이 달라지면
// 중국어 본문의 정사각 그리드가 깨져 세로줄이 안 맞고 성겨 보인다(오너 피드백 2026-08-19,
// 실제 화면 확인). 그래서 폭은 1em으로 균일하게 두고, 겹침은 '긴 병음만 조금 작게'로 푼다.
//
// 실측 근거(Chromium, font-size 20px = 1em, rt 0.5em):
//   rt 폭 — 1~3자 ≤15.8px · 4자 21px · 5자 22.4px · 6자 31px  (한자 base 20px)
//   콘텐츠 예문 2,059개 전수(폭 1em 균일 기준):
//     rt 등배(0.5em)         → 겹침 24.3%, 최대 9.6px
//     길이별 축소(아래 단계) → 겹침  0.5%, 최대 2.0px
//   1~3자가 전체의 70%이고 이 구간은 원래 크기를 유지하므로 대다수 병음의 가독성은 그대로다.

/**
 * 병음 한 음절 → 축소 단계. CSS의 `.word-token ruby[data-syl="N"] rt`가 글자 크기를 줄인다.
 * (폭은 건드리지 않는다 — 정사각 그리드 유지)
 * 대문자는 소문자보다 넓어 같은 글자 수라도 넘치므로 한 단계 올린다(고유명사 Guǎngzhōu).
 * @param {string} reading 병음 음절
 * @returns {'4'|'5'|'6'|undefined} 축소가 불필요하면 undefined(1~3자)
 */
export function rubyWidthStep(reading) {
  const r = String(reading || '');
  if (!r) return undefined;
  const n = [...r].length + (/[A-Z]/.test(r) ? 1 : 0);
  if (n >= 6) return '6';
  if (n === 5) return '5';
  if (n === 4) return '4';
  return undefined;
}
