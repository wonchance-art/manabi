#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import { relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const repositoryRoot = fileURLToPath(new URL('../', import.meta.url));
const outputUrl = new URL('../src/content/refGrammarManifest.js', import.meta.url);

const server = await createServer({
  root: repositoryRoot,
  appType: 'custom',
  logLevel: 'silent',
  server: { middlewareMode: true },
});

try {
  const [{ REF_LANGS }, { getCourseLessonContext }] = await Promise.all([
    server.ssrLoadModule('/src/content/refLangs.js'),
    server.ssrLoadModule('/src/lib/learn/courseMapData.js'),
  ]);

  const languages = {};
  for (const [language, ref] of Object.entries(REF_LANGS)) {
    languages[language] = {
      base: ref.base,
      readKey: ref.readKey,
      flag: ref.flag,
      name: ref.name,
      langCode: ref.langCode,
      blurb: ref.blurb,
      legend: ref.legend,
      pitch: ref.pitch ?? null,
      introLevel: ref.INTRO_LEVEL,
      levelMeta: ref.LEVEL_META,
      levels: ref.LEVEL_META.map((meta) => {
        const bunkei = ref.getBunkei?.(meta.key);
        return {
          key: meta.key,
          vocabCount: ref.countVocab(meta.key),
          bunkeiAvailable: Boolean(bunkei),
          bunkeiChapterSlugs: bunkei
            ? bunkei.themes.flatMap(theme => theme.items).map(item => item.ch).filter(Boolean)
            : [],
          chapters: ref.getGrammarChapters(meta.key).map(chapter => ({
            slug: chapter.slug,
            level: chapter.level,
            order: Number.isFinite(chapter.order) ? chapter.order : null,
            title: chapter.title,
            topic: chapter.topic ?? null,
            summary: chapter.summary ?? null,
            duration: chapter.duration ?? null,
            courseLesson: getCourseLessonContext(
              language,
              chapter.level,
              chapter.slug,
            ),
          })),
        };
      }),
    };
  }

  const source = [
    '// Generated by scripts/build-ref-grammar-manifest.mjs. Do not edit by hand.',
    `export const REF_GRAMMAR_MANIFEST = ${JSON.stringify({ version: 1, languages }, null, 2)};`,
    '',
    'export default REF_GRAMMAR_MANIFEST;',
    '',
  ].join('\n');
  await writeFile(outputUrl, source, 'utf8');

  process.stdout.write(`${JSON.stringify({
    output: relative(repositoryRoot, fileURLToPath(outputUrl)),
    bytes: Buffer.byteLength(source),
    sha256: createHash('sha256').update(source).digest('hex'),
  })}\n`);
} finally {
  await server.close();
}
