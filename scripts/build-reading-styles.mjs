import fs from 'node:fs';
import postcss from 'postcss';
// Preserve the complete published manuscript's rich content styles, scoped to the new reader.
// The edition itself remains immutable; only this generated adaptation is shipped here.
const edition = '7f572327dc67893e9453246c';
const root = postcss.parse(fs.readFileSync(`src/content/textbookEditions/${edition}/style.css`, 'utf8'));
root.walkAtRules('media', rule => { if (rule.params.includes('print')) rule.remove(); });
root.walkRules(rule => {
  if (rule.parent.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
  rule.selectors = rule.selectors.map(selector => {
    if (['html', ':root', 'body'].includes(selector)) return '.book-reading-content';
    return `.book-reading-content ${selector.replace(/^body\s+/, '')}`;
  });
});
let css = root.toString().replaceAll('textbook-page', 'manabi-reader');
fs.writeFileSync('src/components/books/reading-manuscript.css', '/* Generated by scripts/build-reading-styles.mjs. */\n' + css + '\n');
