// Standalone integration test. No network / no production credentials.
// npm install --prefix /tmp/manabi-composer-test-runtime @electric-sql/pglite fake-indexeddb
// COMPOSER_TEST_MODULES=/tmp/manabi-composer-test-runtime/node_modules node scripts/verification/material-composer-storage.mjs
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
const modules = process.env.COMPOSER_TEST_MODULES;
if (!modules) throw new Error('Set COMPOSER_TEST_MODULES to isolated test dependencies.');
const { PGlite } = await import(pathToFileURL(resolve(modules, '@electric-sql/pglite/dist/index.js')).href);
await import(pathToFileURL(resolve(modules, 'fake-indexeddb/auto/index.mjs')).href);
const { readComposerDraft, writeComposerDraft, removeComposerDraft } = await import('../../src/lib/composerDraft.js');
const db = new PGlite();
const owner = '00000000-0000-4000-8000-000000000001', other = '00000000-0000-4000-8000-000000000002';
try {
  await db.exec(`
    create role authenticated; create role anon;
    create schema auth; create schema storage;
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('test.uid', true), '')::uuid $$;
    create function storage.foldername(text) returns text[] language sql immutable as $$ select (string_to_array($1, '/'))[1:array_length(string_to_array($1, '/'), 1)-1] $$;
    create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
    create table storage.objects(id serial primary key,bucket_id text,name text);
    alter table storage.objects enable row level security;
    create table public.reading_materials(id bigint generated by default as identity primary key,owner_id uuid,visibility text,raw_text text,processed_json jsonb);
    alter table public.reading_materials enable row level security;
    create policy owner_material on public.reading_materials for all to authenticated using (owner_id=auth.uid()) with check (owner_id=auth.uid());
    grant usage on schema storage,auth,public to authenticated,anon;
    grant all on storage.objects,public.reading_materials to authenticated;
    grant select on storage.objects,public.reading_materials to anon;
    grant usage on all sequences in schema public,storage to authenticated;
  `);
  await db.exec(await readFile(new URL('../../supabase/migrations/20260907162537_unified_material_composer.sql', import.meta.url), 'utf8'));
  const bucket = (await db.query("select * from storage.buckets where id='material-originals'")).rows[0];
  assert.equal(bucket.public, false); assert.deepEqual(bucket.allowed_mime_types, ['application/pdf','application/epub+zip']);
  await db.exec(`set role authenticated; set test.uid='${owner}';`);
  await db.query("insert into storage.objects(bucket_id,name) values('material-originals',$1)", [`${owner}/attempt/hash.epub`]);
  await assert.rejects(db.query("insert into storage.objects(bucket_id,name) values('material-originals',$1)", [`${other}/attempt/hash.pdf`]), /row-level security/);
  assert.equal((await db.query('select * from storage.objects')).rows.length,1);
  assert.equal((await db.query("update storage.objects set name='overwrite' returning id")).rows.length,0);
  const json = { status:'saved', metadata:{ composer:{version:1,assets:[],links:[]}, importAttempt:'attempt' } };
  await db.query('insert into reading_materials(owner_id,visibility,raw_text,processed_json) values($1,$2,$3,$4)',[owner,'private','',json]);
  await assert.rejects(db.query('insert into reading_materials(owner_id,visibility,processed_json) values($1,$2,$3)',[owner,'private',json]), /unique/);
  for (const visibility of ['public', null]) await assert.rejects(db.query('update reading_materials set visibility=$1',[visibility]), /composer_material_is_private/);
  await db.exec(`set test.uid='${other}';`);
  assert.equal((await db.query('select * from storage.objects')).rows.length,0);
  assert.equal((await db.query('select * from reading_materials')).rows.length,0);
  assert.equal((await db.query('delete from storage.objects returning id')).rows.length,0);
  await db.query('insert into reading_materials(owner_id,visibility,processed_json) values($1,$2,$3)',[other,'private',json]);
  await db.exec('reset role; set role anon;');
  assert.equal((await db.query('select * from storage.objects')).rows.length,0);
  assert.equal((await db.query('select * from reading_materials')).rows.length,0);
  console.log('PASS: SQL applies; private bucket; owner upload/read/delete isolation; no overwrite; attempt uniqueness; public/null visibility rejected; other owner independent; anon blocked.');
} finally { await db.close(); }

const file = { hash:'a'.repeat(64),name:'fixture.epub',kind:'epub',size:5,blob:new Blob(['hello']) };
const draft = { id:'attempt', version:1,title:'원래 제목',body:'내가 쓴 문장',files:[file],links:['https://example.org/'] };
await writeComposerDraft(owner,draft);
await writeComposerDraft(other,{...draft,title:'다른 계정'});
const restored = await readComposerDraft(owner);
assert.equal(restored.title,draft.title); assert.equal(restored.body,draft.body); assert.equal(await restored.files[0].blob.text(),'hello');
await Promise.all(Array.from({length:20},(_,i)=>writeComposerDraft(owner,{...draft,body:`수정 ${i}`})));
assert.equal((await readComposerDraft(owner)).body,'수정 19');
await removeComposerDraft(owner); assert.equal(await readComposerDraft(owner),null);
assert.equal((await readComposerDraft(other)).title,'다른 계정');
assert.equal(await (await readComposerDraft(other)).files[0].blob.text(),'hello');
await assert.rejects(writeComposerDraft('',draft),/ACCOUNT_REQUIRED/);
console.log('PASS: IndexedDB original Blob restored; serialized edits; account isolation; owner-only cleanup; absent account rejected.');
