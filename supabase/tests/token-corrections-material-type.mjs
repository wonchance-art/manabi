/** TOKEN-CORRECTIONS-BIGINT-001 — isolated PostgreSQL verification; no network or live DB connection.
 * 교정 이력(token_corrections).material_id가 reading_materials.id(bigint)와 맞지 않아 이력 저장이 조용히 실패하던 문제.
 * 운영 상태를 모르므로 가능한 출발 상태마다 새 DB에서 20261013150000을 적용해 결과·보존을 확인한다.
 * PGLITE_MODULE=/path/to/@electric-sql/pglite node supabase/tests/token-corrections-material-type.mjs
 */
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { PGlite } = require(process.env.PGLITE_MODULE || '@electric-sql/pglite');

const original = await fs.readFile(new URL('../migrations/20260414000300_token_corrections.sql', import.meta.url), 'utf8');
// 원래 파일은 2026-10-14에 uuid→bigint로 고쳤다. 운영 등 이미 옛 정의로 시도된 DB의 출발 상태를 재현하려고 옛 정의를 되살린다.
const legacyOriginal = original.replace('material_id bigint NOT NULL', 'material_id uuid NOT NULL');
assert.notEqual(legacyOriginal, original, '원래 파일의 material_id 정의가 바뀌면 이 재현도 고친다');
const forward = await fs.readFile(new URL('../migrations/20261013150000_token_corrections_material_bigint.sql', import.meta.url), 'utf8');
const owner = '10000000-0000-0000-0000-000000000001', other = '10000000-0000-0000-0000-000000000002';
let checks = 0;
async function check(name, fn) { await fn(); checks++; console.log(`PASS ${name}`); }

// 운영과 같은 모양: reading_materials.id = bigint identity(m09 운영 메타데이터 fixture와 같은 타입).
async function base() {
  const db = new PGlite();
  await db.exec(`create role anon; create role authenticated; create schema auth;
    create table auth.users(id uuid primary key); grant usage on schema auth to anon, authenticated;
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
    create table public.reading_materials(id bigint generated by default as identity primary key, owner_id uuid, visibility text);
    alter default privileges in schema public grant all on tables to anon, authenticated;
    grant select on public.reading_materials to authenticated;
    insert into auth.users values ('${owner}'), ('${other}');
    insert into public.reading_materials(id, owner_id, visibility) values (7, '${owner}', 'private'), (8, '${other}', 'private');`);
  return db;
}
const rows = async (db, sql, params = []) => (await db.query(sql, params)).rows;
const columnType = async db => (await rows(db, `select format_type(atttypid, atttypmod) as t from pg_attribute
  where attrelid = 'public.token_corrections'::regclass and attname = 'material_id'`))[0]?.t;
async function as(db, user) {
  await db.exec('reset role');
  await db.query("select set_config('request.jwt.claim.sub', $1, false)", [user || '']);
  await db.exec(`set role ${user ? 'authenticated' : 'anon'}`);
}
// 클라이언트(boundaryEditFlow·correctTokenMutation)가 보내는 행과 같은 모양 — material_id는 숫자 자료 id.
// 원래 정의는 외래 키도, 읽기 정책(m.id = material_id)도 uuid↔bigint로 만들 수 없다 — uuid 표가 운영에 있다면
// 외래 키·읽기 정책 없이 손으로 만든 것뿐이다. 그 모양을 재현한다.
const handMadeUuidTable = legacyOriginal.replace(/REFERENCES reading_materials\(id\) ON DELETE CASCADE/, '')
  .replace(/CREATE POLICY "Owner or author can view corrections"[\s\S]*?\);\n/, '');
const insertHistory = (db, user, materialId) => db.query(`insert into public.token_corrections(material_id, token_id, user_id, before_value, after_value)
  values ($1, 'id_0_2', $2, '{"meaning":"옛 뜻"}', '{"meaning":"새 뜻"}')`, [materialId, user]);

// 이력이 정상으로 쓰이고 읽히는지(소유자·작성자만), 자료를 지우면 따라 지워지는지 — 모든 출발 상태의 끝은 같아야 한다.
async function assertWorking(db) {
  assert.equal(await columnType(db), 'bigint');
  await as(db, owner);
  await insertHistory(db, owner, 7);
  assert.deepEqual((await rows(db, 'select token_id, after_value from public.token_corrections where material_id = $1', [7]))
    .map(r => [r.token_id, r.after_value.meaning]), [['id_0_2', '새 뜻']]);
  await as(db, other);
  assert.equal((await rows(db, 'select * from public.token_corrections where material_id = 7')).length, 0, '남의 자료 이력은 안 보인다');
  await assert.rejects(insertHistory(db, owner, 7), /row-level security/, '남의 이름으로 이력을 쓸 수 없다');
  await db.exec('reset role');
  await assert.rejects(insertHistory(db, owner, 999), /foreign key/, '없는 자료 id는 거절');
  await db.exec('delete from public.reading_materials where id = 7');
  assert.equal((await rows(db, 'select * from public.token_corrections where material_id = 7')).length, 0, '자료 삭제 시 이력도 지운다');
}

try {
  await check('수정 전 재현: 옛 정의(uuid)는 bigint 자료 표에서 42804로 실패해 이력 표가 생기지 않는다', async () => {
    const db = await base();
    await assert.rejects(db.exec(legacyOriginal), err => err.code === '42804');
    assert.equal((await rows(db, "select to_regclass('public.token_corrections') as r"))[0].r, null);
  });

  await check('새 DB 체인: 고친 원래 파일 → 정방향 마이그레이션 순서로 멈추지 않고 정상 동작한다', async () => {
    const db = await base();
    await db.exec(original);
    assert.equal(await columnType(db), 'bigint');
    await db.exec(forward);
    assert.equal((await rows(db, "select count(*)::int as n from pg_policies where tablename = 'token_corrections'"))[0].n, 2);
    await assertWorking(db);
  });

  await check('① 표 없음 → bigint로 만들고 이력 쓰기·읽기·RLS·연쇄 삭제가 동작한다', async () => {
    const db = await base();
    await db.exec(forward);
    await assertWorking(db);
  });

  await check('② 이미 bigint → 두 번 적용해도 행·타입이 그대로다(재적용 안전)', async () => {
    const db = await base();
    await db.exec(forward);
    await insertHistory(db, owner, 8);
    const before = await rows(db, 'select * from public.token_corrections order by id');
    await db.exec(forward);
    assert.deepEqual(await rows(db, 'select * from public.token_corrections order by id'), before);
    assert.equal((await rows(db, "select count(*)::int as n from pg_policies where tablename = 'token_corrections'"))[0].n, 2);
    await db.exec('delete from public.token_corrections');
    await assertWorking(db);
  });

  await check('③ uuid 열(외래 키·읽기 정책 없이 손으로 만든 표) + 행 0 → bigint로 바뀌고 외래 키·읽기 정책을 단다', async () => {
    const db = await base();
    await db.exec(handMadeUuidTable);
    assert.equal(await columnType(db), 'uuid');
    // 수정 전 증상: 숫자 자료 id 이력 저장이 거절된다(클라이언트는 console.warn만 남겼다).
    await assert.rejects(insertHistory(db, owner, 7), /invalid input syntax for type uuid/);
    await db.exec(forward);
    await assertWorking(db);
  });

  await check('③ uuid 열에 행이 있으면 아무것도 바꾸지 않고 멈춘다(행 보존)', async () => {
    const db = await base();
    await db.exec(handMadeUuidTable);
    await db.query(`insert into public.token_corrections(material_id, token_id, user_id) values ('20000000-0000-0000-0000-000000000001', 't', $1)`, [owner]);
    const before = await rows(db, 'select * from public.token_corrections');
    await assert.rejects(db.exec(forward), /token_corrections_material_id_unconvertible: 1 rows/);
    assert.equal(await columnType(db), 'uuid');
    assert.deepEqual(await rows(db, 'select * from public.token_corrections'), before);
    assert.equal((await rows(db, "select count(*)::int as n from pg_policies where tablename = 'token_corrections'"))[0].n, 1, '정책도 그대로');
  });

  await check('③ text 열의 숫자 id 행 → 값 그대로 bigint, 자료 없는 옛 행은 남기고 새 행만 외래 키로 검사한다', async () => {
    const db = await base();
    await db.exec(`create table public.token_corrections(id uuid primary key default gen_random_uuid(), material_id text not null, token_id text not null,
      user_id uuid not null references auth.users(id) on delete cascade, before_value jsonb, after_value jsonb, created_at timestamptz not null default now())`);
    await db.query(`insert into public.token_corrections(material_id, token_id, user_id, after_value) values ('7', 'a', $1, '{"meaning":"뜻"}'), ('999', 'b', $1, null)`, [owner]);
    await db.exec(forward);
    assert.equal(await columnType(db), 'bigint');
    assert.deepEqual((await rows(db, 'select material_id, token_id, after_value from public.token_corrections order by token_id'))
      .map(r => [Number(r.material_id), r.token_id, r.after_value]), [[7, 'a', { meaning: '뜻' }], [999, 'b', null]]);
    assert.equal((await rows(db, "select convalidated from pg_constraint where conname = 'token_corrections_material_id_fkey'"))[0].convalidated, false);
    await assert.rejects(insertHistory(db, owner, 998), /foreign key/);
    await db.exec("delete from public.token_corrections where token_id = 'b'");
    await db.exec('delete from public.token_corrections');
    await assertWorking(db);
  });

  console.log(`token-corrections-material-type: ${checks} checks passed`);
} catch (error) {
  console.error(error);
  process.exitCode = 1;
}
