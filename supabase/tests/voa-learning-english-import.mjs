import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import { parseTitle } from '../../src/lib/seriesMeta.js';
import { voaCreditIsAgency, voaCreditIsOwn } from '../../scripts/voa-seed.mjs';

const BASE = await readFile(new URL('../migrations/20261024120000_canonical_analysis_jobs.sql', import.meta.url), 'utf8');
const STARTER = await readFile(new URL('../migrations/20261106210000_starter_analysis_jobs.sql', import.meta.url), 'utf8');
const migration = await readFile(new URL('../migrations/20261112040000_voa_learning_english_import.sql', import.meta.url), 'utf8');
const rollback = await readFile(new URL('../../docs/sql/voa-import-20261109-rollback.sql', import.meta.url), 'utf8');
const admin = '10000000-0000-0000-0000-000000000001';
let checks = 0;
const check = async (name, fn) => { await fn(); checks++; console.log(`PASS ${name}`); };
const pj = (language, status = 'completed') => JSON.stringify({ status, sequence: status === 'idle' ? [] : ['id_0_0'], dictionary: status === 'idle' ? {} : { id_0_0: { text: 'x' } }, metadata: { language } });

async function fresh({ status = 'done', extraIds = 0, vocab = false } = {}) {
  const db = new PGlite();
  await db.exec(`create role anon; create role authenticated; create role service_role; create schema auth;
    create table auth.users(id uuid primary key); grant usage on schema auth to anon,authenticated,service_role;
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    create table profiles(id uuid primary key, role text default 'user');
    create function public.is_admin() returns boolean language sql stable security definer as $$ select exists(select 1 from profiles where id = auth.uid() and role = 'admin') $$;
    create schema fsrs_private; create function fsrs_private.contract_hash_live() returns text language sql as $$ select 'core-fp' $$;
    create table reading_materials(id bigint generated by default as identity primary key, title text, raw_text text, processed_json jsonb, visibility text default 'private', owner_id uuid, direction text not null default 'read');
    insert into auth.users values ('${admin}'); insert into profiles values ('${admin}','admin');`);
  await db.exec(BASE);
  await db.query(`insert into reading_materials(id,title,raw_text,processed_json,visibility,owner_id) values
    (113,'[A1 grammar #1] be','Hello there.',$1,'public','${admin}'), (114,'[A1 grammar #2] have','I have a cat.',$1,'public','${admin}'),
    (200,'mine','x',$2,'private','20000000-0000-0000-0000-000000000002')`, [pj('English', 'idle'), pj('English')]);
  await db.exec(STARTER); // 113 · 114로 starter 작업 한 줄
  await db.exec(`update reading_materials set processed_json = processed_json || '{"status":"completed"}' where id in (113, 114);
    update canonical_analysis_jobs set status = '${status}', chapters_done = 2, attempts = '{"113":1}', llm_usage = '{"calls":5}',
      material_ids = material_ids || array(select g from generate_series(1000, 999 + ${extraIds}) g) where kind = 'starter'`);
  if (vocab) await db.exec('create table public.user_vocabulary (id serial primary key, material_id bigint references reading_materials(id) on delete cascade, source_material_id bigint)');
  return db;
}
const rows = async (db, sql) => (await db.query(sql)).rows;
const snapshot = async (db) => ({
  materials: await rows(db, 'select * from reading_materials order by id'),
  job: (await rows(db, "select id, status, material_ids, current_key, chapters_done, attempts, llm_usage, failure_streak from canonical_analysis_jobs where kind = 'starter'"))[0],
});

const db = await fresh();
const before = await snapshot(db);
await db.exec(migration);
const after = await snapshot(db);
const added = after.materials.filter((m) => !before.materials.some((b) => b.id === m.id));
await check('26편 — 시드 주인 · 공개 · read · idle · English · A2 18 / B1 8 · AFP 각색 WHO 글 없음', async () => {
  assert.equal(added.length, 26); assert.ok(!added.some((m) => /WHO Launches/.test(m.title) || /Agence France/.test(m.raw_text)));
  for (const m of added) {
    assert.equal(m.owner_id, admin); assert.equal(m.visibility, 'public'); assert.equal(m.direction, 'read');
    assert.equal(m.processed_json.status, 'idle'); assert.deepEqual(m.processed_json.sequence, []); assert.deepEqual(m.processed_json.dictionary, {});
    assert.equal(m.processed_json.metadata.language, 'English');
    assert.ok(m.raw_text.length > 1000 && !/Words in This Story|​|  /.test(m.raw_text), m.title);
  }
  const levels = added.map((m) => m.processed_json.metadata.level);
  assert.equal(levels.filter((l) => l === 'A2 초급').length, 18); assert.equal(levels.filter((l) => l === 'B1 중급').length, 8);
});
await check('출처 칸 — kind web · site voa_le · learningenglish.voanews.com https · public-domain · section · 기자 줄(VOA · 통신사 없음) · feed_date', async () => {
  const urls = new Set();
  for (const m of added) {
    const s = m.processed_json.metadata.source;
    assert.deepEqual(Object.keys(s).sort(), ['channel', 'credit', 'feed_date', 'kind', 'license', 'section', 'site', 'url']);
    assert.ok(voaCreditIsOwn(s.credit) && !voaCreditIsAgency(s.credit), s.credit);
    assert.equal(s.kind, 'web'); assert.equal(s.site, 'voa_le'); assert.equal(s.channel, 'VOA Learning English'); assert.equal(s.license, 'public-domain');
    assert.equal(new URL(s.url).protocol, 'https:'); assert.equal(new URL(s.url).hostname, 'learningenglish.voanews.com');
    assert.match(s.feed_date, /^2024-1[12]-\d\d$|^2025-0[1-3]-\d\d$/);
    urls.add(s.url);
  }
  assert.equal(urls.size, 26);
});
await check('제목 parseTitle — 단편 [A2]/[B1] · Academic Writing 두 편만 시리즈 writing #1 · #2, 급수 = 메타 급수', async () => {
  const series = [];
  for (const m of added) {
    const t = parseTitle(m.title);
    assert.ok(t.level && t.display, m.title);
    assert.equal(t.level, m.processed_json.metadata.level.slice(0, 2));
    if (t.series) series.push([t.series, t.num, t.display]);
  }
  assert.deepEqual(series.sort((a, b) => a[1] - b[1]), [
    ['writing', 1, 'Academic Writing: Common Sentence Patterns, Part One'], ['writing', 2, 'Academic Writing: Common Sentence Patterns, Part Two']]);
});
await check('시드 작업 — material_ids 끝에 26 · done → running · 진행 칸(chapters_done · attempts · llm_usage) 그대로', async () => {
  assert.deepEqual(after.job.material_ids.map(Number), [...before.job.material_ids.map(Number), ...added.map((m) => Number(m.id)).sort((a, b) => a - b)]);
  assert.equal(before.job.status, 'done'); assert.equal(after.job.status, 'running');
  assert.equal(after.job.chapters_done, 2); assert.deepEqual(after.job.attempts, { 113: 1 }); assert.deepEqual(after.job.llm_usage, { calls: 5 });
  assert.equal(after.job.failure_streak, 0);
});
await check('다른 자료 그대로 · 재적용 무변경 · 지문 함수 그대로', async () => {
  assert.deepEqual(after.materials.filter((m) => before.materials.some((b) => b.id === m.id)), before.materials);
  await db.exec(migration);
  assert.deepEqual(await snapshot(db), after);
  assert.equal((await rows(db, 'select fsrs_private.contract_hash_live() v'))[0].v, 'core-fp');
});
await check('복원 SQL — 처음 모양(자료 · 작업 줄)', async () => {
  await db.exec(rollback);
  const back = await snapshot(db);
  assert.deepEqual(back.materials, before.materials);
  assert.deepEqual({ ...back.job, chapters_done: before.job.chapters_done }, before.job);
});
await db.close();
