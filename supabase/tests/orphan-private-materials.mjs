/** Local, disposable PGlite only — never connects to Supabase (ORPHAN-MATERIALS-001 · 2026-11-07 KST).
 * 20261107030000_backup_orphan_private_materials + docs/sql 삭제 · 복원.
 * 증명: ① 백업 — 주인 없는 비공개 10행을 모든 열 그대로 · anon/authenticated 닫힘 · 다시 돌려도 덮지 않음
 *       ② 대상 수가 10이 아니면 백업을 만들지 않고, 백업 없이는 삭제가 멈춘다
 *       ③ 삭제는 참조가 하나라도 있거나 지금 행이 백업과 다르면 아무것도 지우지 않는다
 *       ④ 깨끗하면 정확히 10행만 지운다 — 공개 · 주인 있는 자료는 그대로 ⑤ 복원 — 같은 id · 같은 내용(md5) · 다시 돌려도 안전
 *   node supabase/tests/orphan-private-materials.mjs
 */
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

const read = (p) => readFile(new URL(p, import.meta.url), 'utf8');
const BACKUP = await read('../migrations/20261107030000_backup_orphan_private_materials.sql');
const DELETE = await read('../../docs/sql/orphan-private-materials-20261107-delete.sql');
const RESTORE = await read('../../docs/sql/orphan-private-materials-20261107-restore.sql');
const IDS = [1, 5, 7, 13, 14, 15, 16, 17, 18, 30];
const OWNER = '00000000-0000-4000-8000-0000000000aa';
let checks = 0;
const check = async (name, fn) => { await fn(); checks++; console.log(`PASS ${name}`); };

async function fresh({ orphans = IDS } = {}) {
  const db = new PGlite();
  await db.exec(`create role anon nologin; create role authenticated nologin; create role service_role nologin;
    create table public.reading_materials(id bigint generated by default as identity primary key, title text, raw_text text, processed_json jsonb,
      created_at timestamptz not null default now(), visibility text default 'private', owner_id uuid, group_id uuid, source_pdf_id uuid,
      page_start int, page_end int, lesson_explanation_ko text, conversation_script text, direction text not null default 'read', document_json jsonb);
    create table public.user_vocabulary(id bigint primary key, material_id bigint references public.reading_materials(id) on delete cascade);
    create table public.reading_progress(id bigint primary key, material_id bigint references public.reading_materials(id) on delete cascade);`);
  for (const id of orphans) {
    await db.query(`insert into public.reading_materials(id, title, raw_text, processed_json, visibility, owner_id) overriding system value
      values ($1, $2, $3, $4, 'private', null)`, [id, `orphan ${id}`, `本文 ${id}\nline`, JSON.stringify({ status: 'completed', metadata: { language: 'Japanese' } })]);
  }
  await db.query(`insert into public.reading_materials(id, title, raw_text, visibility, owner_id) overriding system value values
    (40, 'public seed', 'x', 'public', null), (41, 'owned private', 'y', 'private', '${OWNER}'), (42, 'owned public', 'z', 'public', '${OWNER}')`);
  return db;
}
const rows = async (db, sql, params = []) => (await db.query(sql, params)).rows;
const fingerprint = (db) => rows(db, `select id, md5(coalesce(title,'')||'|'||coalesce(raw_text,'')||'|'||coalesce(processed_json::text,'')||'|'||created_at::text) h
  from public.reading_materials order by id`);

const db = await fresh();
const before = await fingerprint(db);

await check('① 백업 — 10행 모든 열 · anon/authenticated 닫힘 · 다시 돌려도 덮지 않음', async () => {
  await db.exec(BACKUP);
  const b = await rows(db, `select id from backup_private.reading_materials_orphans_20261107 order by id`);
  assert.deepEqual(b.map(r => Number(r.id)), IDS);
  const same = await rows(db, `select count(*)::int n from backup_private.reading_materials_orphans_20261107 b join public.reading_materials m using (id)
    where row(b.title, b.raw_text, b.processed_json, b.created_at, b.visibility, b.owner_id, b.direction) is not distinct from
          row(m.title, m.raw_text, m.processed_json, m.created_at, m.visibility, m.owner_id, m.direction)`);
  assert.equal(same[0].n, 10);
  const p = (await rows(db, `select has_schema_privilege('anon','backup_private','USAGE') a, has_schema_privilege('authenticated','backup_private','USAGE') b`))[0];
  assert.deepEqual({ ...p }, { a: false, b: false });
  await db.exec(`update backup_private.reading_materials_orphans_20261107 set title = 'kept' where id = 1`);
  await db.exec(BACKUP);
  assert.equal((await rows(db, `select title from backup_private.reading_materials_orphans_20261107 where id = 1`))[0].title, 'kept', 'not rewritten');
  await db.exec(`update backup_private.reading_materials_orphans_20261107 set title = 'orphan 1' where id = 1`);
});

await check('③ 삭제 거절 — 참조가 있거나 지금 행이 백업과 다르면 하나도 지우지 않는다', async () => {
  await db.exec(`insert into public.user_vocabulary values (1, 15)`);
  await assert.rejects(db.exec(DELETE), /still references/);
  await db.exec('rollback');
  await db.exec(`delete from public.user_vocabulary`);
  await db.exec(`update public.reading_materials set raw_text = 'changed' where id = 16`);
  await assert.rejects(db.exec(DELETE), /backup\/live check matched 9 of 10/);
  await db.exec('rollback');
  await db.exec(`update public.reading_materials set raw_text = '本文 16\nline' where id = 16`);
  assert.deepEqual(await fingerprint(db), before, 'nothing deleted or changed');
});

await check('④ 삭제 — 정확히 10행만, 공개 · 주인 있는 자료는 그대로', async () => {
  await db.exec(DELETE);
  const left = await rows(db, `select id from public.reading_materials order by id`);
  assert.deepEqual(left.map(r => Number(r.id)), [40, 41, 42]);
  assert.equal((await rows(db, `select count(*)::int n from backup_private.reading_materials_orphans_20261107`))[0].n, 10, 'backup kept');
});

await check('⑤ 복원 — 같은 id · 같은 내용, 다시 돌려도 안전', async () => {
  await db.exec(RESTORE);
  assert.deepEqual(await fingerprint(db), before);
  await db.exec(RESTORE);
  assert.deepEqual(await fingerprint(db), before);
});
await db.close();

await check('② 대상이 10행이 아니면 백업을 만들지 않고, 백업 없이는 삭제가 멈춘다', async () => {
  const db2 = await fresh({ orphans: IDS.slice(0, 9) });
  await db2.exec(BACKUP);
  assert.equal((await rows(db2, `select to_regclass('backup_private.reading_materials_orphans_20261107') t`))[0].t, null);
  await assert.rejects(db2.exec(DELETE), /backup table missing/);
  await db2.exec('rollback');
  assert.equal((await rows(db2, `select count(*)::int n from public.reading_materials`))[0].n, 12);
  await db2.close();
});

console.log(`orphan-private-materials: ${checks} checks passed`);
